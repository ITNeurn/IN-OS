// 字根总数
#define WUBI_ROOT_COUNT (sizeof(wubi_root_library) / sizeof(wubi_root_t))

// ===================== 汉字拼装映射表（常用汉字 = 字根组合） =====================
// 格式：汉字编码 + 字根序号数组 + 字根数量
typedef struct {
    unsigned char char_code[3];   // 汉字简易标识
    unsigned int root_idx[4];     // 最多4个字根拼装一字
    int root_num;
} wubi_char_map_t;

// 系统常用基础汉字（五笔字根拼装）
static const wubi_char_map_t wubi_char_list[] =
{
    {"一", {0}, 1},
    {"丨", {1}, 1},
    {"人", {14}, 1},
    {"口", {10}, 1},
    {"日", {11}, 1},
    {"月", {12}, 1},
    {"木", {13}, 1},
    {"仁", {7,0}, 2},
    {"冰", {5,0}, 2},
    {"江", {6,10}, 2},
    {"打", {8,0}, 2}
};
#define WUBI_CHAR_COUNT (sizeof(wubi_char_list) / sizeof(wubi_char_map_t))

// ===================== 核心对外接口（给字库管理器调用） =====================
// 清空字体缓冲区
static inline void font_buf_clear(unsigned char *buf)
{
    for(int i = 0; i < CN_FONT_BUF_LEN; i++) buf[i] = 0x00;
}

// 五笔字根拼装：合成完整汉字点阵
void wubi_make_char(unsigned char *out_buf, const unsigned int *root_idx, int root_cnt)
{
    font_buf_clear(out_buf);
    // 多字根叠加拼装（五笔标准组字逻辑）
    for(int r = 0; r < root_cnt; r++)
    {
        int idx = root_idx[r];
        if(idx >= WUBI_ROOT_COUNT) continue;
        // 点阵叠加合并
        for(int i = 0; i < CN_FONT_BUF_LEN; i++)
        {
            out_buf[i] |= wubi_root_library[idx].data[i];
        }
    }
}

// 根据汉字标识，获取最终渲染点阵（对接显示驱动）
int wubi_get_font_dot(const char *char_name, unsigned char *out_buf)
{
    for(int i = 0; i < WUBI_CHAR_COUNT; i++)
    {
        if(wubi_char_list[i].char_code[0] == char_name[0])
        {
            wubi_make_char(out_buf, wubi_char_list[i].root_idx, wubi_char_list[i].root_num);
            return 1; // 成功
        }
    }
    return 0; // 无匹配汉字
}

