#define ASCII_FONT_TOTAL (sizeof(ascii_font_lib) / sizeof(ascii_char_t))

// ===================== 对外标准接口（对接字库管理器、显示驱动） =====================
// 清空字符渲染缓冲区
static inline void ascii_buf_clear(unsigned char *buf)
{
    for(int i = 0; i < ASCII_BUF_SIZE; i++)
        buf[i] = 0x00;
}

// 根据ASCII码获取8*16字符点阵
int ascii_get_dot(unsigned char code, unsigned char *out_buf)
{
    if(code >= ASCII_FONT_TOTAL)
        return 0; // 超出字符范围，返回失败
    ascii_buf_clear(out_buf);
    // 拷贝对应字符点阵到输出缓冲区
    for(int i = 0; i < ASCII_BUF_SIZE; i++)
        out_buf[i] = ascii_font_lib[code][i];
    return 1; // 获取成功
}

