# gen_font.py - 构建期光栅化: 扫描内核源码中实际用到的字符,
# 用 Noto Sans SC (思源黑体, OFL) 渲染为 4bpp 抗锯齿点阵, 生成 font_cn.h
# 用法: python gen_font.py [px]   (默认 22px 正文; 大号数字可再生成独立头)
import os, sys, struct
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.abspath(__file__))
TTF  = r'C:\qemu_iso\font_tools\NotoSansSC.ttf'

# 渲染函数 C 模板 (@P@ = 字号), 依赖 utf8_dec/fcn_blend
RENDER_TPL = r'''
static const fcn@P@_g_t *fcn@P@_find(unsigned cp) {
    int lo = 0, hi = (int)FCN@P@_N - 1;
    while (lo <= hi) {
        int mid = (lo + hi) >> 1;
        unsigned m = fcn@P@_dir[mid].cp;
        if (m == cp) return &fcn@P@_dir[mid];
        if (m < cp) lo = mid + 1; else hi = mid - 1;
    }
    return 0;
}
static void fcn@P@_glyph(int x, int y, const fcn@P@_g_t *g, uint32_t fg) {
    fg = fb_map(fg);
    const unsigned char *bm = fcn@P@_bits + g->off;
    int gx = x + g->xo, gy = y + g->yo;
    int idx = 0;
    for (int r = 0; r < g->h; r++) {
        for (int c = 0; c < g->w; c++) {
            unsigned a = (idx & 1) ? (bm[idx >> 1] & 0xF) : (bm[idx >> 1] >> 4);
            idx++;
            if (a) fcn_blend(gx + c, gy + r, a, fg);
        }
    }
}
static int fcn@P@_text(int x, int y, const char *s, uint32_t fg) {
    while (*s) {
        unsigned cp;
        int n = utf8_dec((const unsigned char *)s, &cp);
        const fcn@P@_g_t *g = fcn@P@_find(cp);
        if (g) { fcn@P@_glyph(x, y, g, fg); x += g->adv; }
        else if (cp < 0x80 && cp >= ' ') { x += FCN@P@_PX / 2; }
        s += n;
    }
    return x;
}
static int fcn@P@_w(const char *s) {
    int x = 0;
    while (*s) {
        unsigned cp;
        int n = utf8_dec((const unsigned char *)s, &cp);
        const fcn@P@_g_t *g = fcn@P@_find(cp);
        x += g ? g->adv : (cp < 0x80 && cp >= ' ' ? FCN@P@_PX / 2 : 0);
        s += n;
    }
    return x;
}
static void fcn@P@_center(int cx, int y, const char *s, uint32_t fg) {
    fcn@P@_text(cx - fcn@P@_w(s) / 2, y, s, fg);
}
'''

PX   = int(sys.argv[1]) if len(sys.argv) > 1 else 22
MODE = sys.argv[2] if len(sys.argv) > 2 else 'full'   # full | digits
OUT  = os.path.join(ROOT, 'font_cn%d.h' % PX)
SCAN = [os.path.join(ROOT, n) for n in
        ('kernel_full.c', 'ui_shell.h', 'cterm.h', 'i2c_hid.h', 'hwprobe.h')]
SCAN = [f for f in SCAN if os.path.exists(f)]   # 驱动头可能尚为桩文件

# ---- 1. 字符集 ----
if MODE == 'digits':
    # 大号字库仅时钟字符
    cps = set(ord(c) for c in '0123456789:')
else:
    cps = set(range(0x20, 0x7F))
    for fn in SCAN:
        if not os.path.exists(fn):
            continue
        with open(fn, 'r', encoding='utf-8') as f:
            for ch in f.read():
                o = ord(ch)
                if o >= 0xA0 and not ch.isspace():
                    cps.add(o)
    # 常见 UI 符号兜底 (源码若用不到也无妨, 体积极小)
    for ch in '℃·—…→←↑↓✓✕●○★☆♪☀☁☂⚙🔒':
        cps.add(ord(ch))
cps = sorted(c for c in cps if c != 0xFEFF)

font = ImageFont.truetype(TTF, PX)
try:
    font.set_variation_by_name('Regular')
except Exception:
    pass
asc, desc = font.getmetrics()
line_h = asc + desc

# ---- 2. 逐字符渲染 (anchor='la': 原点=左bearing/ascender线) ----
PAD = 4
canvas = Image.new('L', (PX + PAD * 2, line_h + PAD * 2), 0)
d = ImageDraw.Draw(canvas)
glyphs = []
for cp in cps:
    ch = chr(cp)
    canvas.paste(0, (0, 0, canvas.size[0], canvas.size[1]))
    d.text((PAD, PAD), ch, font=font, anchor='la', fill=255)
    bbox = canvas.getbbox()
    adv = int(round(font.getlength(ch)))
    if adv < 1:
        adv = PX // 2
    if bbox is None:
        glyphs.append((cp, 0, 0, 0, 0, adv, b''))
        continue
    l, t, r, b = bbox
    w, h = r - l, b - t
    xo, yo = l - PAD, t - PAD          # 相对 ascender 原点
    g = canvas.crop((l, t, r, b)).tobytes()
    # 降为 4bpp (16 级 alpha)
    nb = bytearray((w * h + 1) // 2)
    for i, v in enumerate(g):
        a = v >> 4                     # 0..15
        if i & 1:
            nb[i >> 1] |= (a & 0xF)
        else:
            nb[i >> 1] |= (a << 4)
    glyphs.append((cp, w, h, xo, yo, adv, bytes(nb)))

glyphs.sort(key=lambda z: z[0])

# ---- 3. 生成 C 头 ----
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('// AUTO-GENERATED by gen_font.py - DO NOT EDIT\n')
    f.write('// Noto Sans SC (SIL OFL 1.1) %dpx 4bpp alpha, %d glyphs\n' % (PX, len(glyphs)))
    f.write('#ifndef FONT_CN%d_H\n#define FONT_CN%d_H\n' % (PX, PX))
    f.write('#define FCN%d_PX %d\n#define FCN%d_ASC %d\n#define FCN%d_DESC %d\n#define FCN%d_LH %d\n#define FCN%d_N %d\n\n'
            % (PX, PX, PX, asc, PX, desc, PX, line_h, PX, len(glyphs)))
    f.write('typedef struct { unsigned long off; unsigned short cp; unsigned char adv,w,h; signed char xo,yo; } fcn%d_g_t;\n\n' % PX)
    f.write('static const fcn%d_g_t fcn%d_dir[FCN%d_N] = {\n' % (PX, PX, PX))
    off = 0
    for (cp, w, h, xo, yo, adv, nb) in glyphs:
        f.write('  {%d,0x%04X,%d,%d,%d,%d,%d},\n' % (off, cp, adv & 255, w, h, xo, yo))
        off += len(nb)
    f.write('};\n\n')
    f.write('static const unsigned char fcn%d_bits[%d] = {\n' % (PX, off))
    allbits = b''.join(z[6] for z in glyphs)
    for i in range(0, len(allbits), 32):
        f.write('  ' + ''.join('0x%02X,' % b for b in allbits[i:i+32]) + '\n')
    f.write('};\n\n')
    # ---- 渲染函数 (直接生成, 避开 CPP ## 嵌套) ----
    f.write(RENDER_TPL.replace('@P@', str(PX)))
    f.write('\n#endif\n')

print('px=%d asc=%d desc=%d glyphs=%d bits=%dKB -> %s'
      % (PX, asc, desc, len(glyphs), off // 1024, OUT))
if MODE == 'digits':
    sys.exit(0)

# ---- 4. 预览 PNG (目检字形/对齐) ----
pv = Image.new('RGB', (900, line_h * 4 + 30), (20, 24, 34))
pd = ImageDraw.Draw(pv)
pvf = ImageFont.truetype(TTF, PX)
try:
    pvf.set_variation_by_name('Regular')
except Exception:
    pass
sample = '智能中心 控制中心 显示与亮度 22° 星河入梦 AaGg09:41'
for i in range(3):
    pd.text((14, 8 + i * (line_h + 4)), sample, font=pvf, fill=(235, 240, 250))
    pd.line([(10, 8 + i * (line_h + 4) + asc), (890, 8 + i * (line_h + 4) + asc)], fill=(70, 90, 120))
pv.save(os.path.join(r'C:\qemu_iso', 'font_preview%d.png' % PX))
print('preview -> C:\\qemu_iso\\font_preview%d.png' % PX)
